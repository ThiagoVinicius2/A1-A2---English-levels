/* ============================================================
   Módulo separado: "Erros da Conversa Real"
   Baseado na 9ª rodada: a conversa de hoje sobre hobbies, e só ela.
   Não é um apanhado de várias aulas — são os erros daquela conversa.

   Cada questão declara o seu `kind`, e a forma segue a tarefa:
   - `write`  → campo de digitação. Reescrever, completar, traduzir.
   - `choice` → as 4 opções de sempre, para quando a tarefa é ESCOLHER.
   Quem corrige o texto digitado é o gradeTransAnswer() do módulo de
   tradução, reusado em js/app.js — contração, sinônimo, grafia britânica
   e erro de digitação já estão resolvidos lá.

   POR QUE O PADRÃO 4 MISTURA AS DUAS FORMAS: o corretor ignora caixa de
   propósito, então "Gym" passaria como certo num campo de digitação e o
   exercício de maiúscula morreria. Os dois itens que são só maiúscula
   (gym, piano) viraram `choice`; os que mudam letras (worst, choose,
   singing, one thing, weekends) ficaram digitados, onde a trava de
   resposta curta do convRespostaCurta() os corrige de forma exata.
   Pela mesma razão o Padrão 7, de ortografia, é todo digitado: "habbit"
   tem distância 1 de "habit" e só não passa como typo porque a resposta
   tem uma palavra só.

   Consolidados nas rodadas anteriores e, por isso, fora deste banco:
   - dia + parte do dia (on Wednesday evening), preposição "on" com dias
   - terceira pessoa -s, frases sem verbo, exam / test / free time
   - artigo "a / an", preposições de lugar, listen TO
   - ortografia já vencida (daughter, volleyball, fighting, even though)

   O "to que falta" abre o banco: foi o erro que mais apareceu na conversa
   de hoje, em cinco frases diferentes.

   A mesma frase "It would be cool to have an amazing voice." aparece em
   três padrões (1, 5 e 8) de propósito: foi o erro mais teimoso do dia, e
   cada padrão ataca um pedaço dele — o `to`, o sujeito `It` e a tradução
   inteira a partir do português.
   ============================================================ */

