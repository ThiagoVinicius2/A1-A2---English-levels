/* ============================================================
   Módulo separado: "Erros da Conversa Real"
   Baseado na 10ª rodada: o vocabulário da aula de hoje, e só ele.
   Não é um apanhado de várias aulas — são as palavras daquela conversa.

   A rodada mudou de natureza: até a 9ª o banco vinha dos ERROS da conversa;
   esta vem do VOCABULÁRIO que a aula trabalhou, numa planilha com a frase em
   inglês, a tradução e a palavra-chave, agrupada em quatro blocos. Os quatro
   blocos viraram os quatro padrões, e cada frase da planilha virou uma
   questão no teste e outra na prática.

   Cada questão declara o seu `kind`, e a forma segue a tarefa:
   - `write`  → campo de digitação. Traduzir a frase inteira ou completar.
   - `choice` → as 4 opções de sempre, para quando a tarefa é ESCOLHER entre
     palavras que se confundem: went off x burned out, trap x trapped,
     advice x advices, wisdom x wise, fur x hair, own x rent.
   Quem corrige o texto digitado é o gradeTransAnswer() do módulo de
   tradução, reusado em js/app.js — contração, sinônimo, grafia britânica
   e erro de digitação já estão resolvidos lá.

   Por que tanta frase inteira digitada: o objetivo do bloco é PRODUZIR a
   palavra na frase em que ela mora ("the alarm went off", "I was locked
   out"), não reconhecê-la numa lista. Onde a escolha é mesmo entre duas
   palavras parecidas, aí sim vira `choice`.

   Consolidados nas rodadas anteriores e, por isso, fora deste banco:
   - o "to" que falta antes do verbo, good at + -ing, much x many
   - frases sem sujeito, if real x hipotético, ortografia (habit, career)
   - dia + parte do dia, terceira pessoa -s, artigo "a / an", listen TO

   As quatro frases com "condo" aparecem em dois padrões de propósito: o
   bloco 1 ensina a palavra ("I bought a small condo") e o bloco 4 ensina a
   diferença entre ser dono e alugar, que é onde ela confunde.
   ============================================================ */

